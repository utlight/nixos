#!/usr/bin/env bash
out="${XDG_CONFIG_HOME:-$HOME/.config}/tmuxp"
marker="# generated by tmuxp-gen"
sep=" "

declare -A roots=(
    [work]="$HOME/work/source"
    [personal]="$HOME/personal/source"
)

mkdir -p "$out"

# create missing configs
for label in "${!roots[@]}"; do
    for dir in "${roots[$label]}"/*/; do
        if [ ! -d "$dir" ]; then continue; fi
        name=$(basename "$dir")
        file="$out/$label$sep$name.yaml"
        if [ -e "$file" ]; then continue; fi
        cat >"$file" <<EOF
$marker

session_name: $label$sep$name
start_directory: ${dir%/}
windows:
  - window_name: terminal
    panes: [null]
  - window_name: neovim
    focus: true
    panes: [nvim]
  - window_name: lazygit
    panes: [lazygit]
EOF
    done
done

# delete generated configs whose project directories are gone
shopt -s nullglob
for file in "$out"/*.yaml; do
    read -r first <"$file" || true
    if [ "$first" != "$marker" ]; then continue; fi
    dir=$(sed -n 's/^start_directory: //p' "$file")
    if [ -n "$dir" ] && [ ! -d "$dir" ]; then
        rm "$file"
    fi
done
